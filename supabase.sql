-- 6) Public read policies. Writes are handled by the Netlify server.
DROP POLICY IF EXISTS "Anyone can view profiles" ON public.profiles;
CREATE POLICY "Anyone can view profiles" ON public.profiles FOR SELECT USING (true);

DROP POLICY IF EXISTS "Anyone can view rules" ON public.rules;
CREATE POLICY "Anyone can view rules" ON public.rules FOR SELECT USING (true);

DROP POLICY IF EXISTS "Anyone can view announcements" ON public.announcements;
CREATE POLICY "Anyone can view announcements" ON public.announcements FOR SELECT USING (true);

-- 7) Prevent browser access to password hashes even if policies are changed later.
REVOKE ALL ON public.auth_accounts FROM anon, authenticated;

